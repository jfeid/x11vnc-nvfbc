#!/usr/bin/env bash
#
# encoding-ab.sh - compare Tight compression/quality settings against a server
# isolated from the live session.
#
# Measuring these settings on the running service does not work: the desktop is
# in use, and the only client is a real viewer behind an SSH tunnel and a VDSL
# link. Both are uncontrolled, and both move server CPU by more than the setting
# does. A run on 2026-08-19 came back with compression 6 / quality 9 using 23%
# LESS cpu than 2/8 - physically impossible for an encoder, and entirely
# explained by what else was happening at the time.
#
# So: private x11vnc on a throwaway port, one local rfbcheck.py client, load
# generated by us, and A/B/A ordering so drift is visible rather than assumed.
# NOTES.md puts the harness noise floor at +/-3-8% on loaded scenarios; a delta
# smaller than that is not a result.
#
#   ./encoding-ab.sh                      # default A/B/A: 2:8, 6:9, 2:8
#   ./encoding-ab.sh 0:0 5:5 9:9          # any compress:quality legs you like
#   DUR=20 GEOM=2560x1440+0+0 ./encoding-ab.sh
#
set -euo pipefail

# awk/printf honour LC_NUMERIC, which renders 57.9 as "57,9" in a comma locale
# and silently breaks anything downstream that parses these columns.
export LC_ALL=C

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
BIN="${BIN:-$ROOT/x11vnc/src/x11vnc}"
PORT="${PORT:-5906}"
DUR="${DUR:-15}"
GEOM="${GEOM:-960x540+64+64}"
FPS="${FPS:-60}"
CLIP="${CLIP:-2560x1440+0+0}"
LOG="${LOG:-/tmp/x11vnc-encoding-ab.log}"
: "${DISPLAY:=:1}"
: "${XAUTHORITY:=/run/user/1000/gdm/Xauthority}"
export DISPLAY XAUTHORITY

LEGS=("$@")
[ ${#LEGS[@]} -eq 0 ] && LEGS=(2:8 6:9 2:8)

for leg in "${LEGS[@]}"; do
    [[ "$leg" =~ ^[0-9]:[0-9]$ ]] || { echo "bad leg '$leg', want compress:quality e.g. 6:9" >&2; exit 2; }
done

[ -x "$BIN" ] || { echo "no x11vnc at $BIN (set BIN=)" >&2; exit 2; }
[ -x "$HERE/loadgen" ] || { echo "loadgen not built; run make" >&2; exit 2; }

SRV=""; GEN=""
cleanup() {
    [ -n "$GEN" ] && kill "$GEN" 2>/dev/null || true
    [ -n "$SRV" ] && kill "$SRV" 2>/dev/null || true
}
trap cleanup EXIT INT TERM

ticks() { awk '{print $14+$15}' "/proc/$1/stat" 2>/dev/null || echo 0; }
HZ=$(getconf CLK_TCK)

# -repeat is mandatory for every throwaway server here: x11vnc disables the X
# server's global auto-repeat while a client is attached and only restores it on
# a clean exit, so a killed test server leaves the user's desktop with auto-
# repeat off and nothing in any log to explain it. See README.md.
"$BIN" -display "$DISPLAY" -auth "$XAUTHORITY" -forever -shared -nopw -localhost \
       -repeat -noipv6 -rfbport "$PORT" -nvfbc -nvfbc_nocursor -nvfbc_push \
       -threads -clip "$CLIP" >"$LOG" 2>&1 &
SRV=$!

for _ in $(seq 1 40); do
    ss -ltn 2>/dev/null | grep -q ":$PORT " && break
    sleep 0.25
done
ss -ltn 2>/dev/null | grep -q ":$PORT " || { echo "server never listened on $PORT; see $LOG" >&2; tail -5 "$LOG" >&2; exit 1; }

echo "server pid $SRV on :$PORT   $(basename "$BIN")   clip=$CLIP"
echo "load $GEOM @${FPS}fps blit   ${DUR}s per leg   legs: ${LEGS[*]}"
echo

# One continuous loadgen across every leg: restarting it between legs would
# reseed the pattern and hand each leg different content.
TOTAL=$(( (DUR + 3) * ${#LEGS[@]} + 5 ))
"$HERE/loadgen" -g "$GEOM" -r "$FPS" -d "$TOTAL" -blit -t encoding-ab >/dev/null 2>&1 &
GEN=$!
sleep 1

printf '%-10s %8s %10s %10s %10s %9s\n' leg cpu% MB/s updates/s rects/s jpeg%
for leg in "${LEGS[@]}"; do
    C="${leg%%:*}"; Q="${leg##*:}"
    t0=$(ticks "$SRV"); s0=$(date +%s.%N)
    out=$("$HERE/rfbcheck.py" --port "$PORT" --tight --compress "$C" --quality "$Q" \
                              --stream "$DUR" 2>&1) || { echo "$out" >&2; exit 1; }
    t1=$(ticks "$SRV"); s1=$(date +%s.%N)

    mbs=$(sed -n 's/.*, \([0-9.]*\) MB\/s on the wire.*/\1/p' <<<"$out")
    ups=$(sed -n 's/^stream: \([0-9.]*\) updates\/s.*/\1/p' <<<"$out")
    rps=$(sed -n 's/.*updates\/s, \([0-9.]*\) rects\/s.*/\1/p' <<<"$out")
    jpg=$(sed -n 's/.*jpeg=[0-9]* (\([0-9.]*\)%).*/\1/p' <<<"$out")
    cpu=$(awk -v d=$((t1-t0)) -v hz="$HZ" -v e="$(echo "$s1 - $s0" | bc)" \
              'BEGIN{printf "%.1f", (e>0)? d/hz/e*100 : 0}')

    printf '%-10s %8s %10s %10s %10s %9s\n' "$leg" "$cpu" "${mbs:--}" "${ups:--}" "${rps:--}" "${jpg:--}"
    sleep 2
done

echo
echo "A/B/A: if the two A legs differ by more than the +/-3-8% noise floor,"
echo "drift dominated and the B delta is not attributable."
